export const storefrontPreviewProducts = [...sampleProducts, ...suppliedPhotoProducts].map((product) => {
	const metadata = storefrontPreviewMetadata[product.slug];
	const supplierName = metadata?.supplierName ?? product.supplierName;
	const [makerName, makerLocation] = supplierName.split(" · ");
	const makerSlug = supplierName
		.normalize("NFKD")
		.replace(/[\u0300-\u036f]/g, "")
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, "-")
		.replace(/^-|-$/g, "");
	const availabilityStatus = storefrontPreviewStatuses[product.slug] ?? product.availabilityStatus;

	return {
		...product,
		...metadata,
		isExampleData: true,
		color: storefrontPreviewColors[product.slug] ?? product.color,
		sku: `PNY-${product.slug
			.toUpperCase()
			.replace(/[^A-Z0-9]+/g, "-")
			.replace(/^-|-$/g, "")}`,
		supplierName,
		makerName: makerName.trim(),
		makerSlug,
		makerLocation: makerLocation ?? null,
		onlyAtPonyo: true,
		reservationsOpen: true,
		productionStatus: "collecting" as const,
		availabilityStatus,
		publishedAt: "2026-11-05T15:00:00+09:00",
		isNew: product.isNew ?? (product.tags ?? []).includes("new-arrival"),
		galleryImages: [
			{
				src:
					typeof metadata?.image === "string"
						? metadata.image
						: product.image instanceof Object
							? product.image.src
							: String(product.image),
				alt: product.imageAlt,
			},
		],
		availability: (availabilityStatus === "Available" ||
		!availabilityStatus
			? "available"
			: "unavailable") as Product["availability"],
	};
});

export async function getProducts(
	query = "",
	locale = "en",
): Promise<Product[]> {
	if (PONYO_API_BASE_URL) return ponyoApi.listProducts(query, productTranslationLocale(locale));
	return storefrontPreviewProducts;
}

export async function getProductById(
	id: string,
	locale = "en",
): Promise<Product | undefined> {
	if (PONYO_API_BASE_URL) {
		try {
			return await ponyoApi.getProduct(id, productTranslationLocale(locale));
		} catch {
			return undefined;
		}
	}
	const products = await getProducts("", locale);
	return products.find((product) => product.id === id);
}
